class CoinModel {
  final String id;
  final String symbol;
  final String name;
  final String image;
  final double currentPrice;
  final double marketCap;
  final int marketCapRank;
  final double totalVolume;
  final double high24h;
  final double low24h;
  final double priceChange24h;
  final double priceChangePercentage24h;
  final double circulatingSupply;
  final double? maxSupply;
  final List<double> sparklineIn7d;
  final String description;
  bool isWatchlisted;

  CoinModel({
    required this.id,
    required this.symbol,
    required this.name,
    required this.image,
    required this.currentPrice,
    required this.marketCap,
    required this.marketCapRank,
    required this.totalVolume,
    required this.high24h,
    required this.low24h,
    required this.priceChange24h,
    required this.priceChangePercentage24h,
    required this.circulatingSupply,
    this.maxSupply,
    required this.sparklineIn7d,
    required this.description,
    this.isWatchlisted = false,
  });

  factory CoinModel.fromJson(Map<String, dynamic> json) {
    List<double> sparkline = [];
    if (json['sparkline_in_7d'] != null && json['sparkline_in_7d']['price'] != null) {
      sparkline = (json['sparkline_in_7d']['price'] as List)
          .map((e) => (e as num).toDouble())
          .toList();
    } else {
      sparkline = [
        (json['current_price'] ?? 100.0) * 0.95,
        (json['current_price'] ?? 100.0) * 0.98,
        (json['current_price'] ?? 100.0) * 0.96,
        (json['current_price'] ?? 100.0) * 1.02,
        (json['current_price'] ?? 100.0)
      ];
    }

    return CoinModel(
      id: json['id'] ?? 'unknown',
      symbol: (json['symbol'] ?? '').toString().toUpperCase(),
      name: json['name'] ?? 'Unknown Coin',
      image: json['image'] ?? 'https://assets.coingecko.com/coins/images/1/large/bitcoin.png',
      currentPrice: (json['current_price'] ?? 0.0).toDouble(),
      marketCap: (json['market_cap'] ?? 0.0).toDouble(),
      marketCapRank: json['market_cap_rank'] ?? 999,
      totalVolume: (json['total_volume'] ?? 0.0).toDouble(),
      high24h: (json['high_24h'] ?? 0.0).toDouble(),
      low24h: (json['low_24h'] ?? 0.0).toDouble(),
      priceChange24h: (json['price_change_24h'] ?? 0.0).toDouble(),
      priceChangePercentage24h: (json['price_change_percentage_24h'] ?? 0.0).toDouble(),
      circulatingSupply: (json['circulating_supply'] ?? 0.0).toDouble(),
      maxSupply: json['max_supply'] != null ? (json['max_supply'] as num).toDouble() : null,
      sparklineIn7d: sparkline,
      description: json['description'] ?? 'Detailed research and market insights for ${json['name'] ?? 'this cryptocurrency'}.',
      isWatchlisted: json['isWatchlisted'] ?? false,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'symbol': symbol,
      'name': name,
      'image': image,
      'current_price': currentPrice,
      'market_cap': marketCap,
      'market_cap_rank': marketCapRank,
      'total_volume': totalVolume,
      'high_24h': high24h,
      'low_24h': low24h,
      'price_change_24h': priceChange24h,
      'price_change_percentage_24h': priceChangePercentage24h,
      'circulating_supply': circulatingSupply,
      'max_supply': maxSupply,
      'isWatchlisted': isWatchlisted,
    };
  }

